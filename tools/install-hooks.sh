#!/usr/bin/env bash
#
# Installs this repository's pre-commit hook. Idempotent.
#
#   tools/install-hooks.sh
#
# The hook is a one-line forwarder: it runs tools/check-public-safety.sh on the
# staged files, reading content from the index (--staged), which is exactly what
# will be committed. CI runs the same script, so the two use the same rules.
# The check logic is not copied into the hook: the hook lives under .git/, is not
# versioned, cannot be reviewed and is not distributed, so it must stay thin.
# An existing hook that this installer did not write is never overwritten.
# git commit --no-verify bypasses the hook, which is why CI checks again.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SCANNER="$REPO_ROOT/tools/check-public-safety.sh"
MARK="# check-public-safety pre-commit forwarder"

if [ ! -f "$SCANNER" ]; then
  echo "error: scanner not found: $SCANNER" >&2
  exit 1
fi

# git rev-parse --git-path returns a path relative to REPO_ROOT inside the
# repository; make it absolute. It honours core.hooksPath and linked worktrees.
HOOK_DIR="$(git -C "$REPO_ROOT" rev-parse --git-path hooks)"
case "$HOOK_DIR" in /*) ;; *) HOOK_DIR="$REPO_ROOT/$HOOK_DIR" ;; esac
HOOK="$HOOK_DIR/pre-commit"

if [ -f "$HOOK" ] && ! grep -qF "$MARK" "$HOOK"; then
  echo "an unrecognized pre-commit hook already exists: ${HOOK}; not overwriting. Merge it by hand and rerun." >&2
  exit 1
fi

mkdir -p "$HOOK_DIR"
cat > "$HOOK" <<EOF
#!/usr/bin/env bash
$MARK
# Generated by tools/install-hooks.sh; do not edit. The check logic is in tools/check-public-safety.sh.
# Checks only the staged files (including the new path of a rename, excluding deletions), read from the index.
# Paths are read NUL-separated and unquoted; compatible with bash 3.2 (no mapfile).
set -uo pipefail
root="\$(git rev-parse --show-toplevel)" || exit 1
cd "\$root" || exit 1
files=()
while IFS= read -r -d '' f; do files+=("\$f"); done < <(git -c core.quotePath=false diff --cached --name-only --diff-filter=ACMR -z)
[ "\${#files[@]}" -eq 0 ] && exit 0
exec bash "\$root/tools/check-public-safety.sh" --staged "\$root" "\${files[@]}"
EOF
chmod +x "$HOOK"
echo "installed $HOOK"
echo "check logic: $SCANNER"
